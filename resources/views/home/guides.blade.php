            <article class="guide-card">
                <h2>Do You Need to Replace One Tyre or Two?</h2>
                <p class="guide-copy">It depends on the tread left on your other tyres. If you are replacing two, put the new pair on the rear axle, even on a front wheel drive car, because grip at the back keeps the car steady in the wet, and the older pair goes on the front. Four wheel drive cars may need all four tyres changed, so check your handbook or ask us. If you are replacing one, look at the other tyre on that axle: if it has 3 mm of tread or less, change both, but if it still has plenty of tread, one new tyre is usually fine. Not sure which applies to you? We measure the tread for you, then quote the full price before we set off.</p>
            </article>

            <article class="guide-card">
                <h2>Tyre Age and Safety Checks</h2>
                <p class="guide-copy">Often, yes, if it passes three checks. There is no legal age limit for car tyres in the UK.</p>
                <ol class="guide-steps">
                    <li>First, measure the tread. The legal minimum is 1.6 mm.</li>
                    <li>Second, look for cracks in the sidewall, which show ageing.</li>
                    <li>Third, read the date code on the sidewall. It is four digits after the letters DOT. The first two are the week and the last two are the year, so 2421 means week 24 of 2021.</li>
                </ol>
                <p class="guide-copy">If you see cracks or bulges, change the tyre whatever its age.</p>
            </article>

