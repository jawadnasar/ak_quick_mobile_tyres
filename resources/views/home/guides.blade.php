                <h2>New vs Part-Worn Tyres: UK Legal Requirements</h2>
                <p class="guide-copy">We fit both, so here are the facts. A new tyre has full tread and a known history. A part worn tyre costs less. UK law says a part worn tyre must have at least 2 mm of tread across the full width and all the way round. It must be marked PART WORN in letters at least 4 mm high. It must have no exposed cords, no bulges and no large cuts.</p>
