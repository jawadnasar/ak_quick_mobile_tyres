                <h2>Puncture Repairs and Tyre Damage</h2>
                <p class="guide-copy">Often, yes. A tyre can be repaired when three things are true.</p>
                <ol class="guide-steps md:grid-cols-3">
                    <li>The nail is in the central three quarters of the tread.</li>
                    <li>The hole is 6 mm across or less.</li>
                    <li>The tread is at least 1.6 mm deep all the way round.</li>
                </ol>
                <p class="guide-copy">British Standard BS AU 159 sets these rules. Sidewall damage, splits and bulges mean a new tyre. Leave the nail in until we arrive, because pulling it out lets the air escape. We inspect the tyre first, advise you, repair it, then test it. Tell us if your car has run flat tyres, because they follow different repair rules.</p>
